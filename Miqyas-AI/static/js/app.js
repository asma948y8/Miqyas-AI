const languageToggle = document.getElementById("langToggle");
const fileInput = document.getElementById("fileInput");
const fileLabel = document.getElementById("fileLabel");
const savedLanguage = localStorage.getItem("miqyas-language");

function localizeStaticText(language) {
  document.documentElement.lang = language;
  document.documentElement.dir = language === "ar" ? "rtl" : "ltr";

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const entry = translations[element.dataset.i18n];
    if (entry) element.textContent = entry[language === "ar" ? 0 : 1];
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const entry = translations[element.dataset.i18nPlaceholder];
    if (entry) element.placeholder = entry[language === "ar" ? 0 : 1];
  });

  document.querySelectorAll(".localized-metric").forEach((element) => {
    const value = element.dataset.value;
    const metric = element.dataset.metric;
    if (!value) {
      const summaryMetric = metric.endsWith("-summary");
      element.textContent = summaryMetric
        ? (language === "ar" ? "غير محدد" : "Not set")
        : "—";
      if (language === "ar" && metric === "budget") element.textContent = "غير محددة";
    } else if (metric === "price" || metric === "budget") {
      element.textContent = language === "ar" ? `${value} ر.س` : `SAR ${value}`;
    } else {
      const unit = metric.startsWith("days")
        ? (language === "ar" ? "يوم" : "days")
        : (language === "ar" ? "شهر" : "months");
      element.textContent = `${value} ${unit}`;
    }
  });

  document.querySelectorAll(".warning-text").forEach((element) => {
    if (!element.dataset.warningArabic) element.dataset.warningArabic = element.textContent;
    let text = element.dataset.warningArabic;
    warningTranslations.forEach(([arabic, english]) => {
      text = text.replaceAll(arabic, language === "ar" ? arabic : english);
    });
    element.textContent = text;
  });

  document.querySelectorAll(".flash").forEach((element) => {
    if (!element.dataset.messageArabic) element.dataset.messageArabic = element.textContent;
    let text = element.dataset.messageArabic;
    flashTranslations.forEach(([arabic, english]) => {
      text = text.replace(arabic, language === "ar" ? arabic : english);
    });
    if (language === "en" && text.startsWith("الأعمدة المطلوبة غير موجودة: ")) {
      const columns = text.slice("الأعمدة المطلوبة غير موجودة: ".length);
      const columnNames = [
        ["اسم المورد", "Supplier name"],
        ["مدة التسليم", "Delivery time"],
        ["الضمان", "Warranty"],
        ["السعر", "Price"],
      ];
      text = "Missing required columns: " + columnNames.reduce(
        (result, [arabic, english]) => result.replaceAll(arabic, english),
        columns,
      ).replaceAll("،", ",");
    }
    element.textContent = text;
  });

  const aiLanguageNote = document.querySelector(".ai-language-note");
  if (aiLanguageNote) aiLanguageNote.hidden = language === "ar";

  if (fileLabel && fileInput) {
    const fileName = fileInput.files?.[0]?.name;
    fileLabel.textContent = fileName || translations.dropFile[language === "ar" ? 0 : 1];
  }

  if (languageToggle) {
    languageToggle.innerHTML = language === "ar"
      ? 'EN <span aria-hidden="true">↗</span>'
      : 'عربي <span aria-hidden="true">↗</span>';
    languageToggle.setAttribute("aria-label", language === "ar" ? "Switch to English" : "التبديل إلى العربية");
  }

  const page = document.body.dataset.page;
  if (pageTitles[page]) document.title = pageTitles[page][language === "ar" ? 0 : 1];

  const activeLink = document.querySelector(`nav a[href="${window.location.pathname}"]`);
  if (activeLink) activeLink.classList.add("active");
}

localizeStaticText(savedLanguage === "en" ? "en" : "ar");

if (languageToggle) {
  languageToggle.addEventListener("click", () => {
    const language = document.documentElement.lang === "ar" ? "en" : "ar";
    localStorage.setItem("miqyas-language", language);
    localizeStaticText(language);
  });
}

if (fileInput && fileLabel) {
  fileInput.addEventListener("change", () => {
    const fileName = fileInput.files?.[0]?.name;
    const language = document.documentElement.lang;
    fileLabel.textContent = fileName || translations.dropFile[language === "ar" ? 0 : 1];
  });
}
